def translate_life_span(v):
    if not v:
        return v
    return v.replace("hours", "часов").replace("hour", "час")


def build_ru_spec_groups(spec_groups):
    out = []
    for g in spec_groups or []:
        rows = []
        for row in g.get("rows", []):
            rows.append([translate_cell(c) if c else c for c in row])
        out.append({"title": translate_group_title(g.get("title", "")), "rows": rows})
    return out


def main():
    with open(data_path, encoding="utf-8") as f:
        products = json.load(f)

    translated, skipped = 0, []
    for p in products:
        slug = p["slug"]
        ru = {}

        if p.get("consumable"):
            manu = p["consumable"].get("instrument_manufacturer", "")
            model = p["consumable"].get("instrument_model", "")
            # Avoid "Waters Waters996/2996"-style duplication when the model
            # string already repeats the manufacturer name verbatim.
            if manu and model.lower().startswith(manu.lower()):
                model_display = model
            else:
                model_display = f"{manu} {model}".strip()
            ru["name"] = CONSUMABLE_NAME_OVERRIDES.get(slug, p["name"])
            ru["tagline"] = f"Эквивалентная лампа для {model_display}".strip()
            ru["features"] = []
            ru["description"] = ""
        else:
            hand = RU.get(slug)
            if hand is None:
                skipped.append(slug)
                hand = {}
            ru["name"] = hand.get("name", p["name"])
            ru["tagline"] = hand.get("tagline", p.get("tagline", ""))
            ru["features"] = hand.get("features", p.get("features", []) if not hand else [])
            ru["description"] = hand.get("description", "")

        ru["spec_groups"] = build_ru_spec_groups(p.get("spec_groups"))

        if p.get("consumable"):
            ru["consumable_labels"] = CONSUMABLE_FIELD_LABELS_RU
            ru["life_span"] = translate_life_span(p["consumable"].get("life_span"))

        p["ru"] = ru
        translated += 1

    with open(data_path, "w", encoding="utf-8") as f:
        json.dump(products, f, ensure_ascii=False, indent=2)

    print(f"Translated (ru block added/refreshed) for {translated} products.")
    if skipped:
        print(f"NOTE: {len(skipped)} product(s) had no hand-written RU entry, fell back to EN name/tagline: {skipped}")


if __name__ == "__main__":
    main()
